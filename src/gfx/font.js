// Tiny 3×5 pixel font for neon tubes and pop-ups.
const GLYPHS = {
  A: ['.#.', '#.#', '###', '#.#', '#.#'],
  C: ['.##', '#..', '#..', '#..', '.##'],
  E: ['###', '#..', '##.', '#..', '###'],
  H: ['#.#', '#.#', '###', '#.#', '#.#'],
  L: ['#..', '#..', '#..', '#..', '###'],
  M: ['#.#', '###', '###', '#.#', '#.#'],
  N: ['##.', '#.#', '#.#', '#.#', '#.#'],
  O: ['###', '#.#', '#.#', '#.#', '###'],
  P: ['##.', '#.#', '##.', '#..', '#..'],
  R: ['##.', '#.#', '##.', '#.#', '#.#'],
  S: ['.##', '#..', '.#.', '..#', '##.'],
  T: ['###', '.#.', '.#.', '.#.', '.#.'],
  U: ['#.#', '#.#', '#.#', '#.#', '###'],
  2: ['##.', '..#', '.#.', '#..', '###'],
  4: ['#.#', '#.#', '###', '..#', '..#'],
  '!': ['.#.', '.#.', '.#.', '...', '.#.'],
};

const textWidth = (s) => s.length * 4 - 1;

// Calls fn(x, y, letterIndex) for every lit pixel of `s` drawn at (x, y).
function eachTextPixel(s, x, y, fn) {
  for (let i = 0; i < s.length; i++) {
    const g = GLYPHS[s[i]];
    if (!g) throw new Error(`No glyph for "${s[i]}"`);
    for (let gy = 0; gy < 5; gy++) for (let gx = 0; gx < 3; gx++) if (g[gy][gx] === '#') fn(x + i * 4 + gx, y + gy, i);
  }
}
